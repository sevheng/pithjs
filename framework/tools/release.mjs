// pith/pith.min.js: the whole framework in one file, minified, with the dev-only code (warnings, the
// state registry behind `npm run see --state`) taken out. For deploying a project without a build:
// pith/*.js are the readable sources with dev help, which a no-build site would otherwise ship to
// every visitor (~30 KB gzipped and ten requests, instead of ~10 KB and one).
//   pith release (npm run release in demo/)   rewrites it after changing pith/ (check fails while it's stale)
// To deploy without a build, point the import map at it and preload just it (forDeploy() does this to
// index.html). Development keeps using pith/index.js, so warnings stay on.
// Needs the project's Vite to regenerate (the committed file needs nothing).

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { measureFramework } from './size.mjs';

export const RELEASE_FILE = join(import.meta.dirname, '..', 'pith', 'pith.min.js');
const HEADER = '// Pith, built for production (no dev warnings). Generated by framework/tools/release.mjs from pith/*.js: don\'t edit.\n';

/** @param {string} code the minified framework, from measureFramework() */
export const releaseText = (code) => HEADER + code;

/**
 * Whether pith.min.js matches the current sources.
 * @param {{ code?: string, root?: string }} [options] code: an already-built framework (saves a build)
 * @returns {Promise<{ ok: boolean, skipped?: undefined } | { skipped: string }>}
 */
export async function checkRelease({ code, root } = {}) {
  if (code === undefined) {
    const built = await measureFramework({ root });
    if (built.skipped) return built;
    code = built.code;
  }
  let current = '';
  try {
    current = readFileSync(RELEASE_FILE, 'utf8');
  } catch {}
  return { ok: current === releaseText(code) };
}

/**
 * index.html for a no-build deploy: 'pith' maps to pith.min.js, and its one preload replaces Pith's per-file ones.
 * @param {string} html
 */
export function forDeploy(html) {
  let first = true;
  return html
    .replace(/("pith"\s*:\s*")\/pith\/index\.js"/, '$1/pith/pith.min.js"')
    .replace(/(\n[ \t]*)?<link\b[^>]*\brel="modulepreload"[^>]*\bhref="\/pith\/[^"]*"[^>]*>/g, (tag, lead = '') => {
      if (!first) return '';
      first = false;
      return `${lead}<link rel="modulepreload" href="/pith/pith.min.js">`;
    });
}

if (import.meta.main) {
  const built = await measureFramework();
  if (built.skipped) {
    console.error(`✗ ${built.skipped}`);
    process.exit(1);
  }
  writeFileSync(RELEASE_FILE, releaseText(built.code));
  console.log(`✓ Wrote ${RELEASE_FILE} (${(built.core / 1000).toFixed(1)} KB gzipped)`);
}
