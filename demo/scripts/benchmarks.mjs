// npm run benchmarks: writes app/data/benchmarks.js, the numbers /docs/benchmarks charts, from the raw
// measurements in ../compare/results/measure.json (Pith vs React vs Vue, on the Trading and Spreadsheet apps). tests/benchmarks.test.mjs
// fails while it's out of date.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const MEASURE = join(import.meta.dirname, '..', '..', 'compare', 'results', 'measure.json');
export const DATA = join(import.meta.dirname, '..', 'app', 'data', 'benchmarks.js');
export const hasCompare = () => existsSync(MEASURE);

const PROTOCOLS = { 'http/1.1': 'h1', h2: 'h2' };

export function benchmarksText() {
  const m = JSON.parse(readFileSync(MEASURE, 'utf8'));
  // load[protocol][app][framework] = { ready, fcp, jsKB, jsFiles }
  const load = {};
  for (const r of Object.values(m.load)) {
    const app = ((load[PROTOCOLS[r.protocol]] ??= {})[r.app] ??= {});
    app[r.impl] = { ready: r.ready, fcp: r.fcp, jsKB: r.jsKB, jsFiles: r.jsFiles };
  }
  // runtime[app][operation][framework] = ms, memory[app][state][framework] = MB,
  // stress[app][run][framework] = { fps, frameP50, frameP95, longTasks, longMs } (the raw file is framework-first).
  const flip = (byImpl) => {
    const out = {};
    for (const [impl, values] of Object.entries(byImpl)) for (const [k, v] of Object.entries(values)) (out[k] ??= {})[impl] = v;
    return out;
  };
  const perApp = (byApp, fn) => Object.fromEntries(Object.entries(byApp).map(([app, v]) => [app, fn(v)]));
  const data = {
    measured: m.environment.date.slice(0, 10),
    browser: m.environment.chrome.replace('/', ' '),
    runs: m.environment.runs,
    load,
    runtime: perApp(m.runtime, flip),
    stress: m.stress,
    memory: perApp(m.memory, flip),
  };
  return `// Generated by scripts/benchmarks.mjs (npm run benchmarks) from ../compare/results/measure.json: don't edit.\nexport default ${JSON.stringify(data, null, 2)};\n`;
}

if (import.meta.main) {
  mkdirSync(dirname(DATA), { recursive: true });
  writeFileSync(DATA, benchmarksText());
  console.log(`✓ Wrote ${DATA}`);
}
