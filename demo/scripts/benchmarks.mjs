// npm run benchmarks: writes app/data/benchmarks.js, the numbers /benchmarks charts, from the raw
// measurements in ../compare/results/measure.json (Pith vs React vs Vue). tests/benchmarks.test.mjs
// fails while it's out of date.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const MEASURE = join(import.meta.dirname, '..', '..', 'compare', 'results', 'measure.json');
export const DATA = join(import.meta.dirname, '..', 'app', 'data', 'benchmarks.js');
export const hasCompare = () => existsSync(MEASURE);

const PROTOCOLS = { 'http/1.1': 'h1', h2: 'h2' };

export function benchmarksText() {
  const m = JSON.parse(readFileSync(MEASURE, 'utf8'));
  // load[protocol][page][framework] = { ready, fcp, jsKB, jsFiles }
  const load = {};
  for (const r of Object.values(m.load)) {
    const page = ((load[PROTOCOLS[r.protocol]] ??= {})[r.app] ??= {});
    page[r.impl] = { ready: r.ready, fcp: r.fcp, jsKB: r.jsKB, jsFiles: r.jsFiles };
  }
  // runtime[operation][framework] = ms, memory[state][framework] = MB (the raw file is framework-first).
  const flip = (byImpl) => {
    const out = {};
    for (const [impl, values] of Object.entries(byImpl)) for (const [k, v] of Object.entries(values)) (out[k] ??= {})[impl] = v;
    return out;
  };
  const data = {
    measured: m.environment.date.slice(0, 10),
    browser: m.environment.chrome.replace('/', ' '),
    runs: m.environment.runs,
    load,
    runtime: flip(m.runtime),
    memory: flip(m.memory),
  };
  return `// Generated by scripts/benchmarks.mjs (npm run benchmarks) from ../compare/results/measure.json: don't edit.\nexport default ${JSON.stringify(data, null, 2)};\n`;
}

if (import.meta.main) {
  mkdirSync(dirname(DATA), { recursive: true });
  writeFileSync(DATA, benchmarksText());
  console.log(`✓ Wrote ${DATA}`);
}
