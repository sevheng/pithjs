// npm run examples: writes app/examples/sources.js, the source code /features/<name> shows next to each
// live example (so it shows in every mode: dev, no-build, built and prerendered). tests/examples.test.mjs
// fails while it's out of date.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..', 'app', 'examples');
export const SOURCES = join(dir, 'sources.js');

export function sourcesText() {
  const files = readdirSync(dir).filter((f) => f.endsWith('.js') && f !== 'index.js' && f !== 'sources.js').sort();
  const entries = files.map((f) => `  ${JSON.stringify(f.replace(/\.js$/, ''))}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`);
  return `// Generated by scripts/examples.mjs (npm run examples) from the example files: don't edit.\nexport default {\n${entries.join('\n')}\n};\n`;
}

if (import.meta.main) {
  writeFileSync(SOURCES, sourcesText());
  console.log(`✓ Wrote ${SOURCES}`);
}
